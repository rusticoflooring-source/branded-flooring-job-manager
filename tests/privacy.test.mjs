import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const admin='00000000-0000-0000-0000-000000000001',fitter='00000000-0000-0000-0000-000000000002',other='00000000-0000-0000-0000-000000000003',job='00000000-0000-0000-0000-000000000004';
test('database excludes customer charges and internal overview from fitters, retaining admin access',async()=>{
 const db=new PGlite();
 try{
 await db.exec(`create role anon;create role authenticated;create schema auth;
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to authenticated;grant execute on function auth.uid() to authenticated;
 create table profiles(id uuid primary key,role text,active boolean);
 create table sites(id uuid primary key,name text);
 create table jobs(id uuid primary key,site_id uuid,install_date date,created_at timestamptz default now(),contract_value numeric,extras_value numeric,invoiced_value numeric,paid_value numeric,fitter_payment_due numeric);
 create table variations(id uuid primary key,job_id uuid,amount numeric,description text,created_at timestamptz default now());
 create table job_assignments(job_id uuid,fitter_id uuid,primary key(job_id,fitter_id));
 create function is_admin() returns boolean language sql stable security definer as $$ select exists(select 1 from profiles where id=auth.uid() and role='admin' and active)$$;
 create function assigned_to_job(j uuid) returns boolean language sql stable security definer as $$select exists(select 1 from job_assignments where job_id=j and fitter_id=auth.uid())$$;
 grant select on jobs,variations to authenticated,anon;
 grant select(contract_value) on jobs to authenticated;
 insert into profiles values('${admin}','admin',true),('${fitter}','fitter',true),('${other}','fitter',true);
 insert into jobs(id,contract_value,extras_value,invoiced_value,paid_value,fitter_payment_due) values('${job}',1000,50,1050,200,300);
 insert into job_assignments values('${job}','${fitter}');
 insert into variations(id,job_id,amount,description) values(gen_random_uuid(),'${job}',50,'Extra preparation');`);
 await db.exec(await readFile(new URL('../supabase/migrations/005_admin_overview_price_privacy.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/migrations/006_enforce_price_privacy.sql',import.meta.url),'utf8'));
 await db.exec(`alter table jobs add column instructions text;update jobs set instructions='Customer charge £1050';
 create table job_notes(id uuid default gen_random_uuid(),job_id uuid,body text,visibility text default 'team',created_by uuid);alter table job_notes enable row level security;
 create table job_files(id uuid default gen_random_uuid(),job_id uuid,file_name text,note text,storage_path text);alter table job_files enable row level security;
 create schema storage;create table storage.objects(name text,bucket_id text);alter table storage.objects enable row level security;
 grant usage on schema storage to authenticated;grant select on job_notes,job_files,storage.objects to authenticated;
 create policy notes_read on job_notes for select to authenticated using(is_admin() or (assigned_to_job(job_id) and visibility='team'));
 create policy files_read on job_files for select to authenticated using(is_admin() or assigned_to_job(job_id));
 create policy storage_read on storage.objects for select to authenticated using(true);
 insert into job_notes(job_id,body,created_by) values('${job}','Customer price £1050','${admin}'),('${job}','Fitters wage: £125','${fitter}'),('${job}','Client invoice £1050. Fitters money £125','${fitter}');
 insert into job_files(job_id,file_name,storage_path) values('${job}','site-photo.png','${job}/site-photo.png');
 insert into storage.objects values('${job}/site-photo.png','job-files');`);
 await db.exec(await readFile(new URL('../supabase/migrations/007_financial_text_privacy.sql',import.meta.url),'utf8'));
 await db.exec(`update job_assignments set fitting_cost=125;set role authenticated;select set_config('request.jwt.claim.sub','${admin}',false);`);
 let rows=(await db.query('select * from bf_read_jobs()')).rows;
 assert.equal(rows[0].bf_read_jobs.contract_value,1000);
 await db.exec(`insert into job_admin_tracking(job_id,issues_notes) values('${job}','Private subfloor issue');select set_config('request.jwt.claim.sub','${fitter}',false);`);
 rows=(await db.query('select * from bf_read_jobs()')).rows;
 assert.equal(rows.length,1);const record=rows[0].bf_read_jobs;
 for(const key of ['contract_value','extras_value','invoiced_value','paid_value','fitter_payment_due'])assert.equal(key in record,false,key);
 assert.equal(record.fitting_cost,125);
 assert.equal(record.instructions,'[Admin-only financial information]');
 assert.equal((await db.query('select * from job_notes')).rows.length,1);
 assert.equal((await db.query('select * from job_notes')).rows[0].body,'Fitters wage: £125');
 assert.equal((await db.query('select * from job_files')).rows.length,0);
 assert.equal((await db.query("select * from storage.objects where bucket_id='job-files'")).rows.length,0);
 assert.equal((await db.query(`select * from bf_read_jobs('${job}')`)).rows.length,1);
 assert.equal((await db.query(`select * from bf_read_variations('${job}')`)).rows[0].bf_read_variations.amount,undefined);
 assert.equal((await db.query('select * from job_admin_tracking')).rows.length,0);
 await assert.rejects(db.query('select contract_value from jobs'),/permission denied/);
 await assert.rejects(db.query('select * from jobs'),/permission denied/);
 await assert.rejects(db.query('select amount from variations'),/permission denied/);
 await assert.rejects(db.query(`insert into job_admin_tracking(job_id) values(gen_random_uuid())`),/row-level security/);
 await db.exec(`select set_config('request.jwt.claim.sub','${other}',false);`);
 assert.equal((await db.query('select * from bf_read_jobs()')).rows.length,0);
 assert.equal((await db.query(`select * from bf_read_variations('${job}')`)).rows.length,0);
 await db.exec(`reset role;update profiles set active=false where id='${fitter}';set role authenticated;select set_config('request.jwt.claim.sub','${fitter}',false);`);
 assert.equal((await db.query('select * from bf_read_jobs()')).rows.length,0);
 await db.exec('set role anon');await assert.rejects(db.query('select * from bf_read_jobs()'),/permission denied/);
 }finally{await db.close()}
});
